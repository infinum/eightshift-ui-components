import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { format } from 'oxfmt';
import { glob } from 'glob';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(scriptDir, '..');
const iconsDir = path.join(rootDir, 'lib/icons/ui-icons');
const outputFile = path.join(rootDir, 'lib/icons/generated-icon-loaders.ts');

/**
 * @param {string} _match
 * @param {string} char
 */
const uppercaseMatch = (_match, char) => char.toUpperCase();

/** @param {string} name */
const normalizeIconName = (name) => name.replace(/[-_]+([a-z0-9])/gi, uppercaseMatch).replace(/^([A-Z])/, (char) => char.toLowerCase());

const iconFiles = (await glob('*.tsx', { cwd: iconsDir })).sort();

const fileContents = `${[
	'// This file is auto-generated by scripts/generate-icon-loaders.mjs.',
	'// Do not edit it manually.',
	'',
	"import type { JSX } from 'react';",
	'',
	'export type IconLoader = () => Promise<JSX.Element | null>;',
	'',
	'export const iconLoaders: Record<string, IconLoader> = {',
	...iconFiles.map((file) => {
		const exportName = normalizeIconName(file.replace(/\.tsx$/, ''));
		const importPath = `./ui-icons/${file}`;

		return `\t${exportName}: () => import('${importPath}').then((module) => (module.${exportName} as JSX.Element | undefined) ?? null),`;
	}),
	'};',
	'',
	'export const loadIconByName = (name: string): Promise<JSX.Element | null> => iconLoaders[name]?.() ?? Promise.resolve(null);',
	'export const hasIconLoader = (name: string): boolean => Object.hasOwn(iconLoaders, name);',
	'',
].join('\n')}`;

// Remove the old .js version if it exists
const oldOutputFile = outputFile.replace(/\.ts$/, '.js');
await fs.unlink(oldOutputFile).catch(() => null);

const existingContents = await fs.readFile(outputFile, 'utf8').catch(() => null);

if (existingContents !== fileContents) {
	const formatted = await format(outputFile, fileContents, {
		useTabs: true,
		jsxSingleQuote: true,
		singleQuote: true,
		singleAttributePerLine: true,
		printWidth: 180,
	});

	if (formatted.errors.length > 0) {
		throw new Error(`Failed to format ${outputFile}: ${formatted.errors.map(({ message }) => message).join('; ')}`);
	}

	await fs.writeFile(outputFile, formatted.code);
}
